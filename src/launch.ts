// The shell wrapper and its spawn, plus the Pi-gone watcher. A task is a
// generated script run by the shell, spawned detached with stdout and stderr
// on the log. The command text travels inside a nonce-delimited heredoc, so
// quotes, `#`, `$` and heredocs reach the shell as written: nothing in it is
// ever re-parsed as wrapper text. The script runs the command in a subshell
// (an `exit` in the command cannot skip the marker) and appends the marker
// line that ends the log. A separate watcher, its own detached process,
// kills whatever the command left running when Pi dies.
import { spawn } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { EXIT_MARKER } from "./logs.ts";

/**
 * The wrapper script. `$1` is the log. In `detached` mode the script redirects
 * its own output there, so no file handle crosses the spawn (which Git Bash on
 * Windows cannot do reliably). In `pane` mode the output is teed: the log and
 * the Herdr pane showing the task both get it. The command comes out of a
 * quoted heredoc (no expansion), runs in a subshell so `exit` cannot skip the
 * marker, and the marker carries the nonce so only this wrapper can write a
 * valid one.
 */
export function wrapperScript(command: string, nonce: string, mode: "detached" | "pane" = "detached"): string {
	const body = [
		`__pi_bg_run_cmd=$(cat <<'__PI_BG_RUN_${nonce}__'`,
		command,
		`__PI_BG_RUN_${nonce}__`,
		")",
	];
	const run = ['( eval "$__pi_bg_run_cmd" )', "__pi_bg_run_code=$?", `printf '\\n${EXIT_MARKER}:${nonce}:%s\\n' "$__pi_bg_run_code"`];
	if (mode === "pane") {
		// The marker travels through the tee stream, so it lands in the log after
		// every line of output and the registry's scan order holds. A brace group
		// needs its last command `;`-terminated before the closing brace.
		return [
			"# Generated by pi-bg-run; runs one background task in a pane. $1 is its log.",
			...body,
			`{ ${run.join("; ")} ; } 2>&1 | tee "$1"`,
			"",
		].join("\n");
	}
	return [
		"# Generated by pi-bg-run; runs one background task. $1 is its log.",
		'exec >>"$1" 2>&1',
		...body,
		...run,
		"",
	].join("\n");
}

/**
 * The shell that runs the wrapper: `PI_BG_RUN_SHELL` when set, otherwise Pi's
 * Git Bash discovery order on Windows and bash on POSIX. Pi's own shell config
 * can be passed in from the extension (`getShellConfig`).
 */
export function resolveShell(preferred?: string): string {
	if (preferred !== undefined && preferred !== "") return preferred;
	const fromEnv = process.env.PI_BG_RUN_SHELL;
	if (fromEnv !== undefined && fromEnv !== "") return fromEnv;
	if (process.platform === "win32") {
		const candidates = [
			join(process.env.ProgramFiles ?? "C:\\Program Files", "Git", "bin", "bash.exe"),
			join(process.env["ProgramFiles(x86)"] ?? "C:\\Program Files (x86)", "Git", "bin", "bash.exe"),
		];
		for (const candidate of candidates) if (existsSync(candidate)) return candidate;
		return "bash.exe"; // on PATH: Cygwin, MSYS2, or a custom Git Bash
	}
	return "bash";
}

/** Write the wrapper script next to the log. */
export function writeWrapper(scriptPath: string, command: string, nonce: string, mode: "detached" | "pane" = "detached"): void {
	writeFileSync(scriptPath, wrapperScript(command, nonce, mode), { mode: 0o700 });
}

/**
 * The Pi-gone watcher: its own detached process outside the task's tree. It
 * exits when the task's pid is gone; when Pi dies first it appends the GONE
 * marker to the log and kills the task's tree. A watcher that fails to start
 * leaves the task running without a crash watch (fail open).
 */
export function spawnWatcher(piPid: number, taskPid: number, nonce: string, logPath: string): void {
	const watcherPath = join(dirname(fileURLToPath(import.meta.url)), "bg-watcher.cjs");
	if (!existsSync(watcherPath)) return;
	try {
		const watcher = spawn(process.execPath, [watcherPath, String(piPid), String(taskPid), nonce, logPath], {
			detached: true,
			windowsHide: true,
			stdio: "ignore",
		});
		watcher.unref();
	} catch {
		// fail open: the task runs without a crash watch
	}
}
